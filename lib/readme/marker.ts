import { normalizeReadme, type DraftReadme } from "./config";

// An invisible HTML comment at the end of a published README stores the
// settings it was generated from, so a new draft can start from the README the
// user already has. Base64 keeps the JSON from ever closing the comment ("-->").

const MARKER_PATTERN = /<!-- github-profile-builder:v1 ([A-Za-z0-9+/=]+) -->/;

function toBase64(text: string): string {
  let binary = "";
  for (const byte of new TextEncoder().encode(text)) binary += String.fromCharCode(byte);
  return btoa(binary);
}

function fromBase64(base64: string): string {
  const bytes = Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));
  return new TextDecoder().decode(bytes);
}

export function readmeMarker(readme: DraftReadme): string {
  return `<!-- github-profile-builder:v1 ${toBase64(JSON.stringify(readme))} -->`;
}

/** README settings stored in a README generated by this app, or null. */
export function readReadmeMarker(markdown: string): DraftReadme | null {
  const match = MARKER_PATTERN.exec(markdown);
  if (!match) return null;
  try {
    return normalizeReadme(JSON.parse(fromBase64(match[1])));
  } catch {
    return null; // edited or corrupted marker: start from the defaults
  }
}
