import "server-only";

import { createHash } from "node:crypto";
import { getDraft, type Draft } from "@/lib/drafts/repository";
import { fetchProfile } from "@/lib/github/profile";
import { fetchCurrentProfileReadme } from "@/lib/github/profile-readme";
import { fetchOwnedPublicRepositories, showcaseRepositories } from "@/lib/github/repositories";
import { readGitHubOrNull } from "@/lib/github/server";
import { generateReadme } from "@/lib/readme/generate";
import { APPLY_PARTS, buildApplyPlan, partSnapshot, type ApplyPart, type ApplyPlan } from "./plan";

export type Fingerprints = Record<ApplyPart, string>;

export type ApplyContext =
  | {
      status: "ok";
      draft: Draft;
      plan: ApplyPlan;
      fingerprints: Fingerprints;
      /** The README lists projects but the repositories could not be read: never publish it without them. */
      readmeBlocked: boolean;
    }
  | { status: "notFound" }
  | { status: "github" }
  /** The GitHub login changed after sign-in: paths built from it would be wrong. */
  | { status: "loginChanged" };

/**
 * Loads everything needed to review or apply a draft: the saved draft, the
 * current GitHub state and the README generated by the same function as the
 * editor preview. Used by both the review page and the apply action.
 */
export async function loadApplyContext(
  draftId: string,
  user: { id: number; login: string },
  accessToken: string,
): Promise<ApplyContext> {
  const draft = await getDraft(draftId, user.id);
  if (!draft) return { status: "notFound" };

  const { readme, profile } = draft.content;
  const needsRepositories = readme.sections.projects && readme.projects.length > 0;

  const [current, currentReadme, repositories] = await Promise.all([
    readGitHubOrNull(() => fetchProfile(accessToken), "the profile"),
    readGitHubOrNull(() => fetchCurrentProfileReadme(user.login, accessToken), "the profile README"),
    needsRepositories
      ? readGitHubOrNull(() => fetchOwnedPublicRepositories(accessToken), "repositories")
      : Promise.resolve([]),
  ]);
  if (!current || !currentReadme) return { status: "github" };
  // The profile repository is named after the login; a renamed account must sign in again.
  if (current.login.toLowerCase() !== user.login.toLowerCase()) return { status: "loginChanged" };

  const output = generateReadme({
    readme,
    profile,
    login: user.login,
    repositories: repositories ? showcaseRepositories(repositories, user.login) : [],
  });
  const plan = buildApplyPlan({ current, currentReadme, draft: profile, readme: output });
  const fingerprints = Object.fromEntries(
    APPLY_PARTS.map((part) => [
      part,
      createHash("sha256").update(JSON.stringify(partSnapshot(plan, part))).digest("hex"),
    ]),
  ) as Fingerprints;

  return { status: "ok", draft, plan, fingerprints, readmeBlocked: needsRepositories && repositories === null };
}
